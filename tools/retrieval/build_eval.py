def main():
    index = json.load(open(sys.argv[1]))
    ids_by_name = {}
    ids = set()
    for r in index["art"]:
        i = r[0] + ":" + r[1]
        ids.add(i)
        if r[0] == "line-md":
            ids_by_name.setdefault(r[2], []).append(i)
    fam = {}
    for k, sel in FAMILIES.items():
        out = []
        for s in sel:
            if s.startswith("line:"):
                got = ids_by_name.get(s[5:], [])
                assert got, (k, s)
                out += got
            else:
                assert s in ids, (k, s)
                out.append(s)
        fam[k] = sorted(set(out))
    rows = []
    seen = set()
    for line, fams, hint in LINES:
        assert line not in seen, line
        seen.add(line)
        for f in fams: assert f in fam, (line, f)
        rel = sorted(set(i for f in fams for i in fam[f]))
        rows.append({"line": line, "lang": "en" if line[0].isascii() else "fa", "families": fams, "hint": hint, "relevant": rel})
    json.dump({"families": fam, "lines": rows}, open(sys.argv[2], "w"), ensure_ascii=False, indent=0)
    print(len(rows), "lines,", sum(1 for r in rows if not r["families"]), "abstract,", len(fam), "families")

main()
