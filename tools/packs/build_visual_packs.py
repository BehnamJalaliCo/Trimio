def cube(fn, title, n=33):
    g = np.linspace(0, 1, n, dtype=np.float32)
    b, gg, r = np.meshgrid(g, g, g, indexing="ij")
    rgb = np.stack([r, gg, b], -1).reshape(-1, 3)
    out = np.clip(fn(rgb.reshape(n * n * n, 3)), 0, 1)
    lines = [f'TITLE "{title}"', f"LUT_3D_SIZE {n}", "DOMAIN_MIN 0.0 0.0 0.0", "DOMAIN_MAX 1.0 1.0 1.0"]
    lines += [f"{p[0]:.5f} {p[1]:.5f} {p[2]:.5f}" for p in out]
    return ("\n".join(lines) + "\n").encode("ascii")


def build_overlays(out, key, version):
    rows, files = [], []
    for oid, name, name_fa, kind, blend, make, tags in OVERLAYS:
        rel = f"overlay/{oid}.png"
        files.append((rel, png(make())))
        rows.append({"id": oid, "name": name, "nameFa": name_fa, "kind": kind, "file": rel, "blend": blend, "tags": tags})
    index = json.dumps({"v": 1, "overlays": rows}, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    files = [("pack.json", packlib.pack_json("overlay.film-textures", "Overlay", "بافت و نور فیلم", "Film textures & light", len(rows), "LicenseRef-Trimio")),
             ("overlay/index.json", index)] + files
    return packlib.build("overlay.film-textures", "Overlay", version, files, out, key, "LicenseRef-Trimio",
                         titleFa="بافت و نور فیلم", titleEn="Film textures & light",
                         summaryFa="دانهٔ فیلم، گردوغبار، کاغذ، هاف‌تون، نشت نور و بوکه برای حس سینمایی و چاپی", summaryEn="Film grain, dust, paper, halftone, light leaks and bokeh for a filmic or print feel",
                         items=len(rows))


def build_looks(out, key, version):
    rows, files = [], []
    for lid, name, name_fa, fn, tags in LOOKS:
        rel = f"look/{lid}.cube"
        files.append((rel, cube(fn, name)))
        rows.append({"id": lid, "name": name, "nameFa": name_fa, "kind": "lut", "file": rel, "blend": "", "tags": tags})
    index = json.dumps({"v": 1, "looks": rows}, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    files = [("pack.json", packlib.pack_json("look.cinematic-luts", "Look", "لوک‌های رنگی سینمایی", "Cinematic colour looks", len(rows), "LicenseRef-Trimio")),
             ("look/index.json", index)] + files
    return packlib.build("look.cinematic-luts", "Look", version, files, out, key, "LicenseRef-Trimio",
                         titleFa="لوک‌های رنگی سینمایی", titleEn="Cinematic colour looks",
                         summaryFa="۲۰ لوک رنگی (LUT) مثل سبزآبی‌نارنجی، فیلم گرم، نوآر و ساعت طلایی", summaryEn="20 colour looks (LUTs): teal & orange, warm film, noir, golden hour…",
                         items=len(rows))


def main():
    out = sys.argv[2]
    version = int(sys.argv[sys.argv.index("--version") + 1]) if "--version" in sys.argv else 1
    key = packlib.load_key()
    build_overlays(out, key, version)
    build_looks(out, key, version)
    packlib.write_index(out)


if __name__ == "__main__":
    main()
