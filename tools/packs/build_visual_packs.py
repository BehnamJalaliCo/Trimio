def luma(c):
    return c[..., 0] * 0.2126 + c[..., 1] * 0.7152 + c[..., 2] * 0.0722


def sat(c, k):
    y = luma(c)[..., None]
    return y + (c - y) * k


def contrast(c, k, pivot=0.5):
    return (c - pivot) * k + pivot


def split(c, shadow, highlight, amount):
    y = luma(c)[..., None]
    return c + (np.array(shadow) * (1 - y) + np.array(highlight) * y) * amount


def lift(c, black, white=1.0):
    return black + c * (white - black)


