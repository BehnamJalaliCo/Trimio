def png(arr):
    b = io.BytesIO()
    Image.fromarray(arr).save(b, "PNG", optimize=True)
    return b.getvalue()


def grain(seed, amount, size=1024, coarse=1.0):
    rng = np.random.default_rng(seed)
    n = rng.normal(0.5, 0.5 * amount, (size, size))
    img = Image.fromarray((np.clip(n, 0, 1) * 255).astype(np.uint8))
    if coarse > 1:
        img = img.filter(ImageFilter.GaussianBlur(coarse * 0.4))
    a = np.asarray(img)
    return np.dstack([a, a, a]).astype(np.uint8)


def dust(seed, count, scratches):
    rng = np.random.default_rng(seed)
    img = Image.new("L", (W, H), 0)
    px = img.load()
    for _ in range(count):
        x, y, r = rng.integers(0, W), rng.integers(0, H), rng.uniform(0.6, 3.2)
        v = int(rng.uniform(120, 255))
        for dx in range(-4, 5):
            for dy in range(-4, 5):
                if dx * dx + dy * dy <= r * r and 0 <= x + dx < W and 0 <= y + dy < H:
                    px[x + dx, y + dy] = max(px[x + dx, y + dy], v)
    for _ in range(scratches):
        x = int(rng.integers(0, W))
        v = int(rng.uniform(90, 200))
        wob = rng.uniform(-0.002, 0.002)
        for y in range(H):
            xx = int(x + wob * y * y / 10)
            if 0 <= xx < W:
                px[xx, y] = max(px[xx, y], v)
    a = np.asarray(img.filter(ImageFilter.GaussianBlur(0.6)))
    return np.dstack([a, a, a]).astype(np.uint8)


def paper(seed, tint):
    rng = np.random.default_rng(seed)
    base = rng.normal(0, 1, (H // 4, W // 4))
    img = Image.fromarray(((base - base.min()) / (np.ptp(base) + 1e-9) * 255).astype(np.uint8)).resize((W, H), Image.BICUBIC)
    fine = rng.normal(0, 1, (H, W))
    a = np.asarray(img).astype(np.float32) / 255 * 0.6 + (fine - fine.min()) / (np.ptp(fine) + 1e-9) * 0.4
    a = 0.82 + 0.18 * a
    rgb = np.dstack([a * tint[0], a * tint[1], a * tint[2]])
    return (np.clip(rgb, 0, 1) * 255).astype(np.uint8)


def halftone(step, angle):
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    c, s = np.cos(angle), np.sin(angle)
    u, v = (x * c - y * s) / step, (x * s + y * c) / step
    d = np.sqrt((u - np.round(u)) ** 2 + (v - np.round(v)) ** 2)
    radius = 0.15 + 0.3 * (x / W)
    a = np.where(d < radius, 0, 255).astype(np.uint8)
    return np.dstack([a, a, a])


def leak(seed, colours):
    rng = np.random.default_rng(seed)
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    out = np.zeros((H, W, 3), np.float32)
    for col in colours:
        cx, cy = rng.uniform(-0.2, 1.2) * W, rng.uniform(-0.2, 1.2) * H
        rx, ry = rng.uniform(0.25, 0.7) * W, rng.uniform(0.3, 0.9) * H
        g = np.exp(-(((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2) * 2.2) * rng.uniform(0.6, 1.0)
        out += g[..., None] * np.array(col, np.float32)
    return (np.clip(out, 0, 1) * 255).astype(np.uint8)


def bokeh(seed, colours, count):
    rng = np.random.default_rng(seed)
    img = Image.new("RGB", (W, H), (0, 0, 0))
    layer = np.zeros((H, W, 3), np.float32)
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    for _ in range(count):
        cx, cy, r = rng.uniform(0, W), rng.uniform(0, H), rng.uniform(18, 90)
        col = np.array(colours[rng.integers(0, len(colours))], np.float32) * rng.uniform(0.25, 0.7)
        d = np.sqrt((x - cx) ** 2 + (y - cy) ** 2)
        disc = np.clip((r - d) / 2.5, 0, 1) * (0.75 + 0.25 * np.clip(d / r, 0, 1))
        layer += disc[..., None] * col
    img = Image.fromarray((np.clip(layer, 0, 1) * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(3))
    return np.asarray(img)


